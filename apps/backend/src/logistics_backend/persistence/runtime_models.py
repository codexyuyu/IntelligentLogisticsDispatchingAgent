from sqlalchemy import Table, Column, String, BigInteger, DateTime, Boolean, LargeBinary, ForeignKey, ForeignKeyConstraint, CheckConstraint, UniqueConstraint, Index
from sqlalchemy.dialects.postgresql import UUID, JSONB
from logistics_backend.persistence.resource_models import metadata

requests = Table("job_requests", metadata,
    Column("request_id", UUID(as_uuid=True), primary_key=True),
    Column("version", BigInteger, primary_key=True),
    Column("scope_id", UUID(as_uuid=True), nullable=False),
    Column("family", String(32), nullable=False),
    Column("schema_version", String(16), nullable=False),
    Column("hash", String(64), nullable=False),
    Column("content", LargeBinary, nullable=False),
    CheckConstraint("version > 0 AND schema_version = '2.0.0'", name="request_version"))
jobs = Table("jobs", metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("scope_id", UUID(as_uuid=True), nullable=False),
    Column("actor_id", UUID(as_uuid=True), nullable=False),
    Column("created_by", UUID(as_uuid=True), nullable=False),
    Column("request_id", UUID(as_uuid=True), nullable=False),
    Column("request_version", BigInteger, nullable=False),
    Column("trace_id", UUID(as_uuid=True), nullable=False),
    Column("schema_version", String(16), nullable=False),
    Column("kind", String(32), nullable=False),
    Column("status", String(32), nullable=False),
    Column("command", JSONB(none_as_null=True), nullable=False),
    Column("request_hash", String(64), nullable=False),
    Column("row_version", BigInteger, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    Column("available_at", DateTime(timezone=True), nullable=False),
    Column("deadline_utc", DateTime(timezone=True), nullable=False),
    Column("started_at", DateTime(timezone=True)), Column("finished_at", DateTime(timezone=True)),
    Column("attempt", BigInteger, nullable=False), Column("max_attempts", BigInteger, nullable=False),
    Column("cancel_requested", Boolean, nullable=False),
    Column("lease_owner", UUID(as_uuid=True)), Column("lease_epoch", BigInteger, nullable=False),
    Column("lease_expires_at", DateTime(timezone=True)),
    Column("result_ref", JSONB(none_as_null=True)), Column("failure", JSONB(none_as_null=True)),
    ForeignKeyConstraint(["request_id", "request_version"], ["job_requests.request_id", "job_requests.version"], ondelete="RESTRICT"),
    CheckConstraint("status IN ('queued','running','completed','failed','cancelled')", name="job_status"),
    CheckConstraint("attempt >= 0 AND max_attempts > 0 AND attempt <= max_attempts AND lease_epoch >= 0 AND row_version >= 0", name="job_counters"),
    CheckConstraint("status != 'completed' OR (result_ref IS NOT NULL AND failure IS NULL)", name="job_result"),
    CheckConstraint("status != 'failed' OR (failure IS NOT NULL AND result_ref IS NULL)", name="job_failure"),
    CheckConstraint("(status = 'running') = (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)", name="job_lease"),
    CheckConstraint("schema_version = '2.0.0' AND command->>'schema_version' = schema_version", name="job_schema"))
Index("ix_jobs_claim", jobs.c.status, jobs.c.available_at, jobs.c.created_at)
attempts = Table("job_attempts", metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("schema_version", String(16), nullable=False),
    Column("status", String(32), nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    Column("created_by", UUID(as_uuid=True), nullable=False),
    Column("row_version", BigInteger, nullable=False),
    Column("job_id", UUID(as_uuid=True), ForeignKey("jobs.id", ondelete="RESTRICT"), nullable=False),
    Column("attempt_no", BigInteger, nullable=False), Column("lease_owner", UUID(as_uuid=True), nullable=False),
    Column("lease_epoch", BigInteger, nullable=False), Column("started_at", DateTime(timezone=True), nullable=False),
    Column("finished_at", DateTime(timezone=True), nullable=False), Column("outcome", String(32), nullable=False),
    Column("failure", JSONB(none_as_null=True)), Column("result_ref", JSONB(none_as_null=True)),
    UniqueConstraint("job_id", "attempt_no"),
    CheckConstraint("schema_version = '2.0.0' AND status = 'recorded' AND row_version = 0", name="attempt_metadata"),
    CheckConstraint("finished_at >= started_at AND created_at = updated_at", name="attempt_times"))
idempotency = Table("idempotency", metadata,
    Column("scope_id", UUID(as_uuid=True), primary_key=True),
    Column("actor_id", UUID(as_uuid=True), primary_key=True),
    Column("operation", String(64), primary_key=True), Column("key", String(256), primary_key=True),
    Column("request_hash", String(64), nullable=False), Column("receipt", JSONB(none_as_null=True), nullable=False),
    Column("expires_at", DateTime(timezone=True), nullable=False))

RUNTIME_TABLES = (requests, jobs, attempts, idempotency)
