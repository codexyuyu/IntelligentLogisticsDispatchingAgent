// Generated types come exclusively from the exported backend OpenAPI file.
import fs from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';
const source = new URL('../../contracts/openapi.json', import.meta.url);
const target = new URL('../src/client/generated.ts', import.meta.url);
const output = '// GENERATED by npm run contracts:generate; DO NOT EDIT.\n' + astToString(await openapiTS(source));
const version = fs.readFileSync(new URL('../../contracts/VERSION', import.meta.url), 'utf8').trim();
const metadata = new URL('../src/client/contractVersion.ts', import.meta.url);
const metadataOutput = '// GENERATED by npm run contracts:generate; DO NOT EDIT.\n' +
  `export const CONTRACT_VERSION = ${JSON.stringify(version)} as const;\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output ||
      !fs.existsSync(metadata) || fs.readFileSync(metadata, 'utf8') !== metadataOutput) {
    console.error('Contract drift: run npm run contracts:generate'); process.exit(1);
  }
  console.log('Frontend contract types match OpenAPI');
} else {
  fs.writeFileSync(target, output, 'utf8');
  fs.writeFileSync(metadata, metadataOutput, 'utf8');
  console.log('Generated frontend contract types and version');
}
